def as_list(value: Any) -> list[Any]:
    if value is None:
        return []
    if isinstance(value, list):
        return value
    return [value]


def as_text(value: Any) -> str:
    return value.strip() if isinstance(value, str) else ""


def load_graph(path: Path) -> dict[str, Any]:
    with path.open("rb") as handle:
        loaded = tomllib.load(handle)
    if not isinstance(loaded, dict):  # pragma: no cover - tomllib always returns dict
        return {}
    return loaded


def _require_text(errors: list[str], item: dict[str, Any], key: str, where: str) -> str:
    value = as_text(item.get(key))
    if not value:
        errors.append(f"{where}: missing or non-string `{key}`")
    return value


def _string_list(
    errors: list[str],
    item: dict[str, Any],
    key: str,
    where: str,
    *,
    required: bool = True,
    minimum: int = 0,
) -> list[str]:
    if key not in item:
        if required:
            errors.append(f"{where}: missing `{key}`")
        return []
    value = item[key]
    if not isinstance(value, list) or any(
        not isinstance(entry, str) for entry in value
    ):
        errors.append(f"{where}: `{key}` must be an array of strings")
        return []
    values = [entry.strip() for entry in value]
    if len(values) < minimum or any(not entry for entry in values):
        errors.append(
            f"{where}: `{key}` needs {minimum} non-empty entr{'y' if minimum == 1 else 'ies'}"
        )
    return values


def _unknown_fields(
    errors: list[str], item: dict[str, Any], allowed: set[str], where: str
) -> None:
    for key in sorted(set(item) - allowed):
        errors.append(f"{where}: unknown field `{key}`")


def _table_rows(
    graph: dict[str, Any], table: str, errors: list[str]
) -> list[dict[str, Any]]:
    if table not in graph:
        return []
    value = graph[table]
    if not isinstance(value, list):
        errors.append(f"{table}: must be an array of tables")
        return []
    rows: list[dict[str, Any]] = []
    for index, row in enumerate(value):
        if not isinstance(row, dict):
            errors.append(f"{table}[{index}]: must be a table")
        else:
            rows.append(row)
    return rows


def _index_rows(
    rows: list[dict[str, Any]], table: str, errors: list[str]
) -> dict[str, dict[str, Any]]:
    indexed: dict[str, dict[str, Any]] = {}
    for row in rows:
        row_id = _require_text(errors, row, "id", table)
        if not row_id:
            continue
        if row_id in indexed:
            errors.append(f"{table} `{row_id}`: duplicate id")
        else:
            indexed[row_id] = row
    return indexed


def _v1_error(graph: dict[str, Any]) -> str:
    retired = [f"[[{key}]]" for key in RETIRED_FIELDS if key in graph]
    for table, fields in (
        ("stake", {"status"}),
        (
            "surface",
            {"phase", "checks", "required_evidence", "scope_boundary"},
        ),
        ("opposition", {"recorded_sacrifice", "state"}),
    ):
        for row in as_list(graph.get(table)):
            if isinstance(row, dict):
                retired.extend(f"{table}.{key}" for key in sorted(fields & set(row)))
    detail = ", ".join(sorted(set(retired))) or "version = 1"
    return (
        "graph: v1 review graphs are retired; migrate with "
        f"`references/upgrade-v1.md`. Retired tables/fields present: {detail}"
    )


def validate_graph(graph: dict[str, Any]) -> list[str]:
    """Return all structural v2 schema errors without judging skill prose."""

    if graph.get("version") == 1:
        return [_v1_error(graph)]

    errors: list[str] = []
    _unknown_fields(errors, graph, TOP_FIELDS, "graph")
    if graph.get("version") != GRAPH_VERSION:
        errors.append(f"graph: `version` must be {GRAPH_VERSION}")
    _require_text(errors, graph, "project", "graph")
    for key in ("reviews_dir", "skills_dir"):
        if key not in graph:
            continue
        value = as_text(graph[key])
        if not value:
            errors.append(f"graph: `{key}` must be a non-empty string")
        elif Path(value).is_absolute() or ".." in Path(value).parts:
            errors.append(
                f"graph: `{key}` must be relative, inside the project, and contain no `..`"
            )

    raw_rows = {
        table: _table_rows(graph, table, errors)
        for table in (*TABLE_FIELDS, "decision")
    }
    indexed = {
        table: _index_rows(rows, table, errors) for table, rows in raw_rows.items()
    }

    seen_ids: dict[str, str] = {}
    for table, rows in indexed.items():
        for row_id in rows:
            if row_id in seen_ids:
                errors.append(
                    f"{table} `{row_id}`: id is already used by {seen_ids[row_id]}"
                )
            else:
                seen_ids[row_id] = table

    stakes = indexed["stake"]
    surfaces = indexed["surface"]
    stances = indexed["stance"]
    oppositions = indexed["opposition"]
    unrepresented = indexed["unrepresented"]
    decisions = indexed["decision"]

    stake_stances: dict[str, list[str]] = {stake_id: [] for stake_id in stakes}
    stake_unopposed: dict[str, list[str]] = {stake_id: [] for stake_id in stakes}
    surface_stances: dict[str, list[str]] = {surface_id: [] for surface_id in surfaces}
    stance_axes: dict[str, set[str]] = {stance_id: set() for stance_id in stances}

    for stake_id, stake in stakes.items():
        where = f"stake `{stake_id}`"
        _unknown_fields(errors, stake, TABLE_FIELDS["stake"], where)
        _require_text(errors, stake, "objective", where)
        _string_list(errors, stake, "evidence", where, minimum=1)

    for surface_id, surface in surfaces.items():
        where = f"surface `{surface_id}`"
        _unknown_fields(errors, surface, TABLE_FIELDS["surface"], where)
        _require_text(errors, surface, "title", where)
        _require_text(errors, surface, "skill", where)
        _string_list(errors, surface, "trigger", where, minimum=1)
        _string_list(errors, surface, "owner_documents", where, minimum=1)
        for key in ("paths", "exclude_paths", "keywords", "contends"):
            _string_list(errors, surface, key, where, required=False)
        for axis in _string_list(errors, surface, "contends", where, required=False):
            if axis not in oppositions:
                errors.append(f"{where}: `contends` names unknown opposition `{axis}`")
        unopposed = as_text(surface.get("unopposed_stake"))
        if unopposed:
            if unopposed not in stakes:
                errors.append(f"{where}: unknown unopposed stake `{unopposed}`")
            else:
                stake_unopposed[unopposed].append(surface_id)

    for stance_id, stance in stances.items():
        where = f"stance `{stance_id}`"
        _unknown_fields(errors, stance, TABLE_FIELDS["stance"], where)
        _require_text(errors, stance, "objective", where)
        _require_text(errors, stance, "skill", where)
        for surface_id in _string_list(errors, stance, "surfaces", where, minimum=1):
            if surface_id not in surfaces:
                errors.append(f"{where}: unknown surface `{surface_id}`")
                continue
            surface_stances[surface_id].append(stance_id)
            if not as_list(surfaces[surface_id].get("contends")):
                errors.append(
                    f"{where}: reads surface `{surface_id}` whose `contends` is empty"
                )
        for stake_id in _string_list(errors, stance, "stakes", where, minimum=1):
            if stake_id not in stakes:
                errors.append(f"{where}: unknown stake `{stake_id}`")
            else:
                stake_stances[stake_id].append(stance_id)
        harms = stance.get("accepted_harm")
        if not isinstance(harms, list) or not harms:
            errors.append(f"{where}: `accepted_harm` needs at least one table")
            continue
        for harm in harms:
            if not isinstance(harm, dict):
                errors.append(f"{where}: each `accepted_harm` entry must be a table")
                continue
            _unknown_fields(
                errors, harm, {"payer", "payer_stance", "cost", "resource"}, where
            )
            _require_text(errors, harm, "payer", where)
            _require_text(errors, harm, "cost", where)
            payer_stance = as_text(harm.get("payer_stance"))
            if payer_stance and payer_stance not in stances:
                errors.append(f"{where}: unknown payer stance `{payer_stance}`")
            if payer_stance == stance_id:
                errors.append(f"{where}: a stance cannot pay itself")

    for stake_id in stakes:
        represented = bool(stake_stances[stake_id])
        unopposed = bool(stake_unopposed[stake_id])
        if represented and unopposed:
            errors.append(
                f"stake `{stake_id}`: cannot be both stance-represented and unopposed"
            )
        elif not represented and not unopposed:
            errors.append(
                f"stake `{stake_id}`: is orphaned; name it from a stance or one "
                "surface's `unopposed_stake`"
            )

    for surface_id in surfaces:
        if not surface_stances[surface_id] and not as_text(
            surfaces[surface_id].get("unopposed_stake")
        ):
            errors.append(
                f"surface `{surface_id}`: has no stance and no `unopposed_stake`"
            )

    for opposition_id, opposition in oppositions.items():
        where = f"opposition `{opposition_id}`"
        _unknown_fields(errors, opposition, TABLE_FIELDS["opposition"], where)
        _require_text(errors, opposition, "contended_resource", where)
        members = _string_list(errors, opposition, "stances", where, minimum=2)
        if len(set(members)) != len(members):
            errors.append(f"{where}: lists the same stance twice")
        for member in members:
            if member not in stances:
                errors.append(f"{where}: unknown stance `{member}`")
            else:
                stance_axes[member].add(opposition_id)

    for stance_id, stance in stances.items():
        opponents = {
            other
            for axis in stance_axes[stance_id]
            for other in _string_list(
                [], oppositions[axis], "stances", "", required=False
            )
            if other != stance_id
        }
        if not opponents:
            errors.append(f"stance `{stance_id}`: is in no opposition")
        payers = {
            as_text(harm.get("payer_stance"))
            for harm in as_list(stance.get("accepted_harm"))
            if isinstance(harm, dict) and as_text(harm.get("payer_stance"))
        }
        for opponent in sorted(opponents - payers):
            errors.append(
                f"stance `{stance_id}`: opposes `{opponent}` but does not name "
                "it as `payer_stance` in `accepted_harm`"
            )
        for payer in sorted(payers - opponents):
            errors.append(
                f"stance `{stance_id}`: names `{payer}` as payer without an opposition"
            )

    for unrepresented_id, row in unrepresented.items():
        where = f"unrepresented `{unrepresented_id}`"
        _unknown_fields(errors, row, TABLE_FIELDS["unrepresented"], where)
        for key in ("stake", "where", "why"):
            _require_text(errors, row, key, where)
        if "forge_when" in row:
            _require_text(errors, row, "forge_when", where)

    decision_axes: set[str] = set()
    for decision_id, decision in decisions.items():
        where = f"decision `{decision_id}`"
        kind = as_text(decision.get("kind"))
        if kind not in DECISION_KIND_FIELDS:
            errors.append(f"{where}: `kind` must be joint, sacrifice, or open")
            allowed = DECISION_COMMON_FIELDS
        else:
            allowed = DECISION_COMMON_FIELDS | DECISION_KIND_FIELDS[kind]
        _unknown_fields(errors, decision, allowed, where)
        for key in ("summary", "owner_document", "reopen_when"):
            _require_text(errors, decision, key, where)
        axes = _string_list(errors, decision, "axes", where, required=False)
        surfaces_for_decision = _string_list(
            errors, decision, "surfaces", where, required=False
        )
        members = _string_list(errors, decision, "stances", where, required=False)
        if not axes and not surfaces_for_decision:
            errors.append(f"{where}: needs at least one of `axes` or `surfaces`")
        for axis in axes:
            if axis not in oppositions:
                errors.append(f"{where}: unknown opposition `{axis}`")
            else:
                decision_axes.add(axis)
        for surface_id in surfaces_for_decision:
            if surface_id not in surfaces:
                errors.append(f"{where}: unknown surface `{surface_id}`")
        for member in members:
            if member not in stances:
                errors.append(f"{where}: unknown stance `{member}`")

        if kind == "joint":
            if not axes:
                errors.append(f"{where}: a joint decision needs `axes`")
            for axis in axes:
                if axis not in oppositions:
                    continue
                axis_members = set(as_list(oppositions[axis].get("stances")))
                missing = axis_members - set(members)
                if missing:
                    errors.append(
                        f"{where}: joint decision does not cover both sides of "
                        f"`{axis}`: missing {', '.join(sorted(missing))}"
                    )
        elif kind == "sacrifice":
            status = _require_text(errors, decision, "status", where)
            if status and status not in DECISION_STATUSES:
                errors.append(
                    f"{where}: `status` must be decided, implemented, or verified"
                )
            decided_by = _require_text(errors, decision, "decided_by", where)
            if decided_by and decided_by not in {"user", "orchestrator"}:
                errors.append(f"{where}: `decided_by` must be user or orchestrator")
            _require_text(errors, decision, "given_up", where)
            sacrificed = _require_text(errors, decision, "sacrificed", where)
            if (
                sacrificed
                and sacrificed not in stances
                and sacrificed not in unrepresented
            ):
                errors.append(f"{where}: unknown sacrificed id `{sacrificed}`")
            if sacrificed in stances and axes:
                axis_stances = {
                    member
                    for axis in axes
                    if axis in oppositions
                    for member in as_list(oppositions[axis].get("stances"))
                }
                if sacrificed not in axis_stances:
                    errors.append(
                        f"{where}: sacrificed stance `{sacrificed}` is not in its axes"
                    )
        elif kind == "open":
            _require_text(errors, decision, "owner", where)
            _require_text(errors, decision, "next_action", where)
        if kind and not axes and kind not in {"sacrifice", "open"}:
            errors.append(f"{where}: a decision without axes must be sacrifice or open")

    for axis in oppositions:
        if axis not in decision_axes:
            errors.append(
                f"opposition `{axis}`: is not referenced by any decision's axes"
            )

    return errors


def _wrap(text: str, width: int = 88) -> list[str]:
    lines: list[str] = []
    current = ""
    for word in text.split():
        candidate = f"{current} {word}".strip()
        if current and len(candidate) > width:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines or [""]


def _frontmatter(name: str, description: str, metadata: dict[str, str]) -> str:
    lines = ["---", f"name: {name}", "description: >-"]
    lines.extend(f"  {line}" for line in _wrap(description))
    lines.extend(["disable-model-invocation: true", "metadata:"])
    lines.extend(f"  {key}: {value}" for key, value in metadata.items())
    lines.append("---")
    return "\n".join(lines)


def _generated_header(graph_path: Path) -> str:
    return f"{GENERATED_PREFIX} from {graph_path.name}. Do not edit by hand. -->"


def _cell(value: Any) -> str:
    if isinstance(value, list):
        value = ", ".join(as_text(item) for item in value)
    return as_text(value).replace("|", "\\|").replace("\n", " ")


def _opposition_indexes(graph: dict[str, Any]) -> dict[str, list[str]]:
    axes: dict[str, list[str]] = {}
    for opposition in as_list(graph.get("opposition")):
        axis = as_text(opposition.get("id"))
        for member in as_list(opposition.get("stances")):
            axes.setdefault(as_text(member), []).append(axis)
    return axes


def _relative_link(project_root: Path, registry_path: Path, raw: str) -> str:
    target = project_root / raw.split("#", 1)[0]
    return Path(os.path.relpath(target, registry_path.parent)).as_posix()


def render_registry(
    graph: dict[str, Any], graph_path: Path, project_root: Path, registry_path: Path
) -> str:
    project = as_text(graph.get("project"))
    registry_id = f"{project}-stance-registry"
    description = (
        f"Use to find which stance owns a question in {project}, which stances "
        "oppose each other, and which decisions must be reopened. Do not use as "
        "a review stance itself."
    )
    lines = [
        _frontmatter(
            registry_id,
            description,
            {"hydra-graph": project, "hydra-kind": "registry"},
        ),
        "",
        _generated_header(graph_path),
        "",
        f"# {project} stance registry",
        "",
        "The canonical topology is the review graph. Edit the graph, then regenerate.",
        "",
        "## Stances",
        "",
        "| Stance | Axis | Objective | Accepts |",
        "| --- | --- | --- | --- |",
    ]
    axes = _opposition_indexes(graph)
    for stance in as_list(graph.get("stance")):
        stance_id = as_text(stance.get("id"))
        skill = as_text(stance.get("skill"))
        stance_cell = (
            f"[`{stance_id}`]({_relative_link(project_root, registry_path, skill)})"
            if skill
            else f"`{stance_id}`"
        )
        accepts = "; ".join(
            f"`{as_text(harm.get('payer'))}` pays: {as_text(harm.get('cost'))}"
            for harm in as_list(stance.get("accepted_harm"))
            if isinstance(harm, dict)
        )
        lines.append(
            f"| {stance_cell} | {_cell(axes.get(stance_id, []))} | "
            f"{_cell(stance.get('objective'))} | {_cell(accepts)} |"
        )
    lines.extend(
        [
            "",
            "## Oppositions",
            "",
            "| Axis | Pair | Contended resource |",
            "| --- | --- | --- |",
        ]
    )
    for opposition in as_list(graph.get("opposition")):
        members = [as_text(item) for item in as_list(opposition.get("stances"))]
        pair = " vs ".join(f"`{member}`" for member in members)
        lines.append(
            f"| `{_cell(opposition.get('id'))}` | {pair} | "
            f"{_cell(opposition.get('contended_resource'))} |"
        )
    if as_list(graph.get("unrepresented")):
        lines.extend(
            [
                "",
                "## Unrepresented stakes",
                "",
                "| Id | Stake | Where it appears | Why no stance holds it |",
                "| --- | --- | --- | --- |",
            ]
        )
        for row in as_list(graph.get("unrepresented")):
            lines.append(
                f"| `{_cell(row.get('id'))}` | {_cell(row.get('stake'))} | "
                f"{_cell(row.get('where'))} | {_cell(row.get('why'))} |"
            )
    if as_list(graph.get("decision")):
        lines.extend(
            [
                "",
                "## Decisions",
                "",
                "| Id | Kind | Summary | Status | Owner document | Reopen when |",
                "| --- | --- | --- | --- | --- | --- |",
            ]
        )
        for decision in as_list(graph.get("decision")):
            lines.append(
                f"| `{_cell(decision.get('id'))}` | {_cell(decision.get('kind'))} | "
                f"{_cell(decision.get('summary'))} | {_cell(decision.get('status'))} | "
                f"{_cell(decision.get('owner_document'))} | "
                f"{_cell(decision.get('reopen_when'))} |"
            )
    lines.append("")
    return "\n".join(lines)


def render_all(
    graph: dict[str, Any], graph_path: Path, project_root: Path
) -> dict[Path, str]:
    skills_dir = as_text(graph.get("skills_dir")) or ".agents/skills"
    registry_path = (
        project_root
        / skills_dir
        / f"{as_text(graph.get('project'))}-stance-registry"
        / "SKILL.md"
    )
    return {
        registry_path: render_registry(graph, graph_path, project_root, registry_path)
    }


def write_rendered(rendered: dict[Path, str]) -> list[Path]:
    written: list[Path] = []
    for path, content in sorted(rendered.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def _normalize_generated(text: str) -> str:
    lines: list[str] = []
    for raw in text.splitlines():
        line = raw.rstrip()
        if line.startswith("|") and line.endswith("|"):
            cells = [cell.strip() for cell in line.strip("|").split("|")]
            if cells and all(set(cell) <= set("-: ") for cell in cells):
                cells = ["---" for _ in cells]
            line = "| " + " | ".join(cells) + " |"
        lines.append(line)
    collapsed: list[str] = []
    for line in lines:
        if line == "" and collapsed and collapsed[-1] == "":
            continue
        collapsed.append(line)
    return "\n".join(collapsed).strip()


def check_rendered(rendered: dict[Path, str]) -> list[str]:
    errors: list[str] = []
    for path, expected in sorted(rendered.items()):
        if not path.exists():
            errors.append(f"generated registry is missing: {path}")
            continue
        actual = path.read_text(encoding="utf-8")
        if _normalize_generated(actual) != _normalize_generated(expected):
            errors.append(
                f"generated registry is stale: {path}. Run `hydra_graph.py generate`."
            )
    return errors


def _glob_regex(pattern: str) -> re.Pattern[str]:
    index = 0
    parts: list[str] = []
    while index < len(pattern):
        if pattern.startswith("**/", index):
            parts.append("(?:.*/)?")
            index += 3
        elif pattern.startswith("**", index):
            parts.append(".*")
            index += 2
        elif pattern[index] == "*":
            parts.append("[^/]*")
            index += 1
        elif pattern[index] == "?":
            parts.append("[^/]")
            index += 1
        else:
            parts.append(re.escape(pattern[index]))
            index += 1
    return re.compile("^" + "".join(parts) + "$")


def _path_matches(path: str, patterns: Iterable[Any]) -> bool:
    return any(_glob_regex(as_text(pattern)).match(path) for pattern in patterns)


def _without_anchor(raw: Any) -> str:
    return as_text(raw).split("#", 1)[0]


def _surface_matches(
    surface: dict[str, Any],
    changed_files: list[str],
    added_lines: dict[str, list[str]],
) -> list[str]:
    matched: list[str] = []
    excluded = as_list(surface.get("exclude_paths"))
    owners = {_without_anchor(raw) for raw in as_list(surface.get("owner_documents"))}
    for path in changed_files:
        if _path_matches(path, excluded):
            continue
        for pattern in as_list(surface.get("paths")):
            if _glob_regex(as_text(pattern)).match(path):
                matched.append(f"path:{pattern}:{path}")
        if path in owners:
            matched.append(f"owner_document:{path}")
        added = "\n".join(added_lines.get(path, []))
        for keyword_value in as_list(surface.get("keywords")):
            keyword = as_text(keyword_value)
            if keyword and re.search(
                rf"(?<!\w){re.escape(keyword)}(?!\w)", added, re.IGNORECASE
            ):
                matched.append(f"keyword:{keyword}:{path}")
    return sorted(set(matched))


def _surface_indexes(
    graph: dict[str, Any],
) -> tuple[dict[str, dict[str, Any]], dict[str, list[str]]]:
    surfaces = {as_text(item.get("id")): item for item in as_list(graph.get("surface"))}
    readers = {surface_id: [] for surface_id in surfaces}
    for stance in as_list(graph.get("stance")):
        stance_id = as_text(stance.get("id"))
        for surface_id in as_list(stance.get("surfaces")):
            surface_id = as_text(surface_id)
            if surface_id in readers:
                readers[surface_id].append(stance_id)
    return surfaces, readers


def route(
    graph: dict[str, Any],
    changed_files: list[str],
    *,
    added_lines: dict[str, list[str]] | None = None,
    all_surfaces: bool = False,
    include_axes: dict[str, str] | None = None,
    skip_reasons: dict[str, str] | None = None,
    keywords_evaluated: bool = False,
) -> dict[str, Any]:
    """Select surfaces, axes, and every stance on each selected axis."""

    added_lines = added_lines or {}
    include_axes = include_axes or {}
    skip_reasons = skip_reasons or {}
    changed_files = sorted(set(changed_files))
    surfaces, readers = _surface_indexes(graph)
    oppositions = {
        as_text(item.get("id")): item for item in as_list(graph.get("opposition"))
    }
    stances = {as_text(item.get("id")): item for item in as_list(graph.get("stance"))}
    stance_axes = _opposition_indexes(graph)

    selected_surfaces: dict[str, list[str]] = {}
    for surface_id, surface in surfaces.items():
        matched = (
            ["all"]
            if all_surfaces
            else _surface_matches(surface, changed_files, added_lines)
        )
        if matched:
            selected_surfaces[surface_id] = matched

    selected_axes: set[str] = set()
    for surface_id in selected_surfaces:
        selected_axes.update(
            as_text(axis) for axis in as_list(surfaces[surface_id].get("contends"))
        )
    selected_axes.discard("")

    changed_set = set(changed_files)
    for stake in as_list(graph.get("stake")):
        evidence = {_without_anchor(raw) for raw in as_list(stake.get("evidence"))}
        if not changed_set & evidence:
            continue
        stake_id = as_text(stake.get("id"))
        for stance_id, stance in stances.items():
            if stake_id in as_list(stance.get("stakes")):
                selected_axes.update(stance_axes.get(stance_id, []))
    selected_axes.update(include_axes)
    axes_before_skip = set(selected_axes)
    active_axes = selected_axes - set(skip_reasons)

    selected_stances = {
        member
        for axis in active_axes
        for member in as_list(oppositions[axis].get("stances"))
    }
    unselected_readers = []
    for stance_id in sorted(stances):
        if stance_id in selected_stances:
            continue
        read = sorted(
            set(readers_for_surface(readers, stance_id)) & set(selected_surfaces)
        )
        if read:
            unselected_readers.append(
                {
                    "id": stance_id,
                    "surfaces": read,
                    "axes": sorted(stance_axes.get(stance_id, [])),
                }
            )

    prior_decisions = []
    for decision in as_list(graph.get("decision")):
        decision_axis_set = {as_text(axis) for axis in as_list(decision.get("axes"))}
        if decision_axis_set:
            selected = bool(decision_axis_set & axes_before_skip)
        else:
            selected = bool(
                {as_text(item) for item in as_list(decision.get("surfaces"))}
                & set(selected_surfaces)
            )
        if selected:
            prior_decisions.append(
                {
                    "id": as_text(decision.get("id")),
                    "kind": as_text(decision.get("kind")),
                }
            )

    unopposed = [
        {
            "surface": surface_id,
            "stake": as_text(surfaces[surface_id].get("unopposed_stake")),
            "skill": as_text(surfaces[surface_id].get("skill")),
        }
        for surface_id in sorted(selected_surfaces)
        if as_text(surfaces[surface_id].get("unopposed_stake"))
    ]
    if axes_before_skip and not active_axes:
        status = "no_reviewers"
    elif not active_axes and unopposed:
        status = "unopposed_only"
    elif not active_axes:
        status = "no_match"
    else:
        status = "ok"

    return {
        "status": status,
        "changed_files": changed_files,
        "keywords_evaluated": keywords_evaluated,
        "surfaces": [
            {
                "id": surface_id,
                "title": as_text(surfaces[surface_id].get("title")),
                "matched_by": matched,
            }
            for surface_id, matched in sorted(selected_surfaces.items())
        ],
        "axes": sorted(active_axes),
        "stances": [
            {
                "id": stance_id,
                "objective": as_text(stances[stance_id].get("objective")),
                "axes": sorted(stance_axes.get(stance_id, [])),
            }
            for stance_id in sorted(selected_stances)
        ],
        "oppositions": [
            {
                "id": axis,
                "stances": as_list(oppositions[axis].get("stances")),
                "contended_resource": as_text(
                    oppositions[axis].get("contended_resource")
                ),
            }
            for axis in sorted(active_axes)
        ],
        "unselected_readers": unselected_readers,
        "prior_decisions": prior_decisions,
        "unopposed": unopposed,
        "included": [
            {"axis": axis, "reason": include_axes[axis]}
            for axis in sorted(include_axes)
        ],
        "skipped": [
            {"axis": axis, "reason": skip_reasons[axis]}
            for axis in sorted(skip_reasons)
        ],
    }


def readers_for_surface(readers: dict[str, list[str]], stance_id: str) -> list[str]:
    return [surface_id for surface_id, ids in readers.items() if stance_id in ids]


def render_route_markdown(result: dict[str, Any]) -> str:
    lines = [f"# Review route: {result['status']}", ""]
    if result.get("error"):
        lines.extend([as_text(result["error"]), ""])
    for error in result.get("errors", []):
        lines.append(f"- {error}")
    if result.get("errors"):
        lines.append("")
    if result.get("pass_file"):
        lines.extend([f"Pass file: {result['pass_file']}", ""])
    lines.extend(["## Surfaces", ""])
    for surface in result.get("surfaces", []):
        lines.append(
            f"- `{surface['id']}` — {surface['title']} "
            f"({', '.join(surface['matched_by'])})"
        )
    lines.extend(["", "## Axes", ""])
    lines.extend(f"- `{axis}`" for axis in result.get("axes", []))
    if result.get("oppositions"):
        lines.extend(["", "## Oppositions", ""])
        for opposition in result["oppositions"]:
            members = ", ".join(opposition["stances"])
            lines.append(
                f"- `{opposition['id']}` — {opposition['contended_resource']} "
                f"(stances: {members})"
            )
    lines.extend(["", "## Stances", ""])
    for stance in result.get("stances", []):
        lines.append(f"- `{stance['id']}` — {stance['objective']}")
    if result.get("unselected_readers"):
        lines.extend(["", "## Unselected readers", ""])
        for stance in result["unselected_readers"]:
            lines.append(
                f"- `{stance['id']}` — surfaces: {', '.join(stance['surfaces'])}; "
                f"axes: {', '.join(stance['axes'])}"
            )
    if result.get("prior_decisions"):
        lines.extend(["", "## Decisions this change must re-check", ""])
        for decision in result["prior_decisions"]:
            lines.append(f"- `{decision['id']}` ({decision['kind']})")
    if result.get("unopposed"):
        lines.extend(["", "## Unopposed checks", ""])
        for item in result["unopposed"]:
            lines.append(
                f"- `{item['surface']}` checks `{item['stake']}`; run `{item['skill']}`"
            )
    if result.get("included"):
        lines.extend(["", "## Included axes", ""])
        for item in result["included"]:
            lines.append(f"- `{item['axis']}` — {item['reason']}")
    if result.get("skipped"):
        lines.extend(["", "## Skipped axes", ""])
        for item in result["skipped"]:
            lines.append(f"- `{item['axis']}` — {item['reason']}")
    lines.extend(
        [
            "",
            f"Keywords evaluated: {str(result.get('keywords_evaluated', False)).lower()}",
            "",
        ]
    )
    return "\n".join(lines)


